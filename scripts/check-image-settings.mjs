// Real Electron UI and file transactions against temporary synthetic products.
// No merchant network, login session, original Excel or material is modified.
import {_electron as electron} from 'playwright-core';
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {imageFixture} from '../test/pdd-fixtures.mjs';
const require=createRequire(import.meta.url),root=path.resolve(import.meta.dirname,'..');
const temp=await fs.realpath(await fs.mkdtemp(path.join(os.tmpdir(),'wq-image-ui-'))),materials=path.join(temp,'materials'),product=path.join(materials,'商品'),data=path.join(temp,'appdata');
let app;const checks=[];
const check=(name,ok)=>{assert(ok,name);checks.push(name);};
try{
  const fixture=await imageFixture(product);await fs.mkdir(data);
  await fs.writeFile(path.join(data,'config.json'),JSON.stringify({schema:1,platform:'pdd',materialsRoot:materials,materialRoots:{pdd:materials},shops:[],selectedProductIds:[],selectedShopIds:[]}));
  const env={...process.env,WQ_APP_DATA_DIR:data};delete env.ELECTRON_RUN_AS_NODE;
  app=await electron.launch({executablePath:process.env.WQ_TEST_APP||require('electron'),args:process.env.WQ_TEST_APP?[]:[root],env,timeout:30000});
  const win=await app.firstWindow();win.setDefaultTimeout(12000);const errors=[];win.on('pageerror',e=>errors.push(e.message));
  await win.getByRole('button',{name:'一键编号',exact:true}).waitFor();
  const originalBook=await fs.readFile(fixture.file),originalNames=(await fs.readdir(fixture.main)).sort();
  await win.getByRole('button',{name:'选择首图',exact:true}).click();
  await win.waitForFunction(()=>[...document.querySelectorAll('.first-image-option img')].length===5&&[...document.querySelectorAll('.first-image-option img')].every(i=>i.complete&&i.naturalWidth>0));
  check('按钮旁显示5张缩略图，没有打开大抽屉或切换页面',await win.locator('#overlay-root .drawer').count()===0&&await win.locator('#breadcrumb').innerText()==='批量上架');
  check('打开选图不会修改商品表',Buffer.compare(await fs.readFile(fixture.file),originalBook)===0);
  await win.evaluate(()=>document.dispatchEvent(new Event('scroll')));
  await win.waitForTimeout(200);
  check('页面滚动不误关闭首图面板',await win.locator('#image-picker:not(.leaving)').count()===1);
  await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].setSize(1280,900));
  await win.waitForTimeout(200);
  check('窗口缩放后首图面板仍保持打开',await win.locator('#image-picker:not(.leaving)').count()===1);
  await win.getByRole('button',{name:'选择图片 03',exact:true}).click();
  await win.evaluate(()=>{render();const log=document.createElement('div');document.body.append(log);log.dispatchEvent(new Event('scroll'));log.remove();});
  await win.waitForTimeout(200);
  check('状态刷新及日志滚动保留首图选择',await win.locator('.first-image-option.selected').getAttribute('data-id')==='03');
  check('缩放后确认按钮在窗口内',await win.getByRole('button',{name:'确认首图',exact:true}).evaluate(e=>{const r=e.getBoundingClientRect();return r.top>=36&&r.bottom<=innerHeight&&r.left>=0&&r.right<=innerWidth;}));
  await win.locator('#breadcrumb').click();await win.locator('#image-picker').waitFor({state:'detached'});
  check('点外部收起且原图表格不变',JSON.stringify((await fs.readdir(fixture.main)).sort())===JSON.stringify(originalNames)&&Buffer.compare(await fs.readFile(fixture.file),originalBook)===0);
  await win.getByRole('button',{name:'一键编号',exact:true}).click();
  await win.getByText('主图已编号，原图备份已保留',{exact:true}).waitFor();
  check('一键编号直接完成且保留备份',JSON.stringify((await fs.readdir(fixture.main)).sort())===JSON.stringify(['01.png','02.png','03.png','04.png','05.png']));
  await win.getByRole('button',{name:'选择首图',exact:true}).click();
  await win.getByRole('button',{name:'选择图片 03',exact:true}).click();
  check('只有一组首图选择',await win.locator('.first-image-option.selected').count()===1&&await win.locator('input[name="detail-first"]').count()===0);
  await win.getByRole('button',{name:'确认首图',exact:true}).click();
  await win.getByText('首图已确认',{exact:true}).waitFor();
  let state=await win.evaluate(()=>window.wqapp.getState());
  check('主图与详情第二张使用同一首图',state.products[0].ok&&state.products[0].mediaPlan.main[0]==='03'&&state.products[0].mediaPlan.details[0]==='尺码图'&&state.products[0].mediaPlan.details[1]==='03');
  check('自动生成10张轮播和17张详情',state.products[0].mediaPlan.main.length===10&&state.products[0].mediaPlan.details.length===17);
  await win.getByRole('button',{name:'选择首图',exact:true}).click();
  check('再次打开回显唯一首图',await win.locator('.first-image-option.selected').getAttribute('data-id')==='03');
  await win.getByRole('button',{name:'确认首图',exact:true}).click();await win.getByText('首图设置未变化',{exact:true}).waitFor();
  check('重复确认不产生额外备份',(await fs.readdir(path.join(product,'.wq-image-settings'))).length===2);
  await win.getByRole('button',{name:'查看',exact:true}).click();
  await win.locator('.drawer').evaluate(e=>e.scrollTop=e.scrollHeight);
  check('资料抽屉显示图片计划且关闭键始终可见',await win.getByText('本次图片计划',{exact:true}).isVisible()&&await win.getByRole('button',{name:'关闭',exact:true}).isVisible());
  await win.locator('.overlay').click({position:{x:25,y:360}});await win.getByRole('dialog').waitFor({state:'detached'});
  check('资料抽屉滚到底后点击左侧可关闭，背景未切页',await win.locator('#breadcrumb').innerText()==='批量上架');
  check('关闭后恢复页面滚动',await win.evaluate(()=>document.body.style.overflow!=='hidden'));
  await app.close();app=null;
  app=await electron.launch({executablePath:process.env.WQ_TEST_APP||require('electron'),args:process.env.WQ_TEST_APP?[]:[root],env,timeout:30000});
  const reopened=await app.firstWindow();await reopened.getByRole('button',{name:'选择首图',exact:true}).click();
  await reopened.locator('#image-picker').waitFor();
  check('App重启仍从Excel读取唯一首图',await reopened.locator('.first-image-option.selected').getAttribute('data-id')==='03');
  check('原生渲染没有JavaScript错误',errors.length===0);
  await reopened.waitForTimeout(250);
  check('选图小面板没有横向整页溢出',await reopened.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  const out=process.env.WQ_AUDIT_DIR||path.join(root,'output/pdd-044-audit');await fs.mkdir(out,{recursive:true});await reopened.screenshot({path:path.join(out,process.env.WQ_TEST_APP?'installed-image-settings.png':'image-settings.png')});
  const result={checks:checks.length,names:checks,packaged:!!process.env.WQ_TEST_APP,merchantMutation:false};
  await fs.writeFile(path.join(out,process.env.WQ_TEST_APP?'installed-ui-check.json':'ui-check.json'),JSON.stringify(result,null,2));console.log(JSON.stringify(result));
}catch(e){if(app)console.error((await app.firstWindow()).isClosed()?e.message:await (await app.firstWindow()).locator('body').innerText());throw e;}
finally{if(app)await app.close();await fs.rm(temp,{recursive:true,force:true});}
